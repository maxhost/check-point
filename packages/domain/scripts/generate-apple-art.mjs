import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "../../..");
const logoSource = path.join(
  repoRoot,
  "apps/consumer/public/wallet-logo-trama-v1.png",
);
const stripSource = path.join(
  repoRoot,
  "docs/design-explorations/apple-wallet-trama-strip-v1.svg",
);
const output = path.join(
  repoRoot,
  "packages/domain/src/server/wallet/apple-art.ts",
);

const source = {
  logo: await readFile(logoSource),
  strip: await readFile(stripSource),
};
const formats = [
  ["icon", 38, 38, source.logo],
  ["logo", 50, 50, source.logo],
  ["strip", 375, 144, source.strip],
];
const entries = [];
for (const [name, width, height, image] of formats) {
  for (const scale of [1, 2, 3]) {
    const filename = `${name}${scale === 1 ? "" : `@${scale}x`}.png`;
    const png = await sharp(image)
      .resize(width * scale, height * scale)
      .png({ compressionLevel: 9 })
      .toBuffer();
    entries.push([filename, png.toString("base64")]);
  }
}

const lines = [
  "// Generated by packages/domain/scripts/generate-apple-art.mjs.",
  "// Sources: wallet-logo-trama-v1.png and apple-wallet-trama-strip-v1.svg.",
  "// Embedded bytes keep the artwork in the server bundle that signs each .pkpass.",
  "export const APPLE_PASS_ART: Record<string, Uint8Array> = {",
  ...entries.map(
    ([name, base64]) =>
      `  ${JSON.stringify(name)}: new Uint8Array(Buffer.from(${JSON.stringify(base64)}, "base64")),`,
  ),
  "};",
  "",
];
await writeFile(output, lines.join("\n"));
process.stdout.write(
  `Wrote ${entries.length} Apple Wallet PNG assets to ${output}\n`,
);
